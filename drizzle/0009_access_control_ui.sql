-- Configuration d'affichage de l'écran « Droits d'accès ». La sécurité réelle
-- reste portée par roles / role_permissions / project_access ; cette table ne
-- conserve que le nom de profil et le libellé de périmètre choisis dans l'UI.
CREATE TABLE IF NOT EXISTS member_access_settings (
  organization_id TEXT NOT NULL REFERENCES organizations(id),
  user_id TEXT NOT NULL REFERENCES profiles(id),
  profile_name TEXT NOT NULL,
  scope TEXT NOT NULL,
  updated_by TEXT NOT NULL REFERENCES profiles(id),
  updated_at TEXT NOT NULL,
  PRIMARY KEY (organization_id, user_id)
);

