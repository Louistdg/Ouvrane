INSERT OR IGNORE INTO role_permissions(role_id, permission_code)
SELECT r.id, p.code
FROM roles r
JOIN role_defaults d ON d.role_code = r.code
JOIN permissions p ON p.code = d.permission_code
WHERE NOT EXISTS (
  SELECT 1 FROM role_permissions existing WHERE existing.role_id = r.id
);
